/** Canonical Uniswap V3 infra proven by DERIVING equality vs the configured row from the generated
 *  evidence's RAW facts (kami 24254 #2/#3) — never a summary boolean. */
function v3InfraProven(row: V3ChainRow, ev: V3ChainEvidence | undefined): boolean {
  const i = ev?.infra;
  return (
    !!i &&
    ev.chainId === row.id &&
    i.chainId === row.id &&
    i.numeraire.address.toLowerCase() === row.numeraire.address.toLowerCase() &&
    i.numeraire.decimals === row.numeraire.decimals &&
    i.numeraire.symbol === row.numeraire.symbol &&
    i.factory.address.toLowerCase() === row.v3Factory.toLowerCase() &&
    i.factory.feeTier === row.feeTier &&
    i.factory.tickSpacing > 0 &&
    i.factory.codeSize > 0 &&
    i.positionManager.address.toLowerCase() === row.positionManager.toLowerCase() &&
    i.positionManager.factoryBinding.toLowerCase() === row.v3Factory.toLowerCase() &&
    i.positionManager.codeSize > 0 &&
    !!i.verifiedAtBlock
  );
}

/** Hyde's OWN launchpad deployed + gojo's signed cross-bind/round-trip — the LAUNCH-enabled gate (kami #2).
 *  Canonical Uniswap infra alone is NOT enough: no deployed pad ⇒ not available. */
function v3LaunchProven(row: V3ChainRow, ev: V3ChainEvidence | undefined): boolean {
  const l = ev?.launch;
  const configured = row.launchpad;
  return (
    !!l &&
    isRealAddress(l.pad) &&
    isRealAddress(l.locker) &&
    !!l.implementation &&
    l.implementation.toLowerCase() === configured.implementation.toLowerCase() &&
    l.pad.toLowerCase() === configured.pad.toLowerCase() &&
    l.locker.toLowerCase() === configured.locker.toLowerCase() &&
    !!l.implementationCodeHash &&
    l.implementationCodeHash.toLowerCase() === configured.implementationCodeHash.toLowerCase() &&
    !!l.padCodeHash &&
    l.padCodeHash.toLowerCase() === configured.padCodeHash.toLowerCase() &&
    !!l.lockerCodeHash &&
    l.lockerCodeHash.toLowerCase() === configured.lockerCodeHash.toLowerCase() &&
    (l.implementationCodeSize ?? 0) > 0 &&
    l.padCodeSize > 0 &&
    l.lockerCodeSize > 0 &&
    // gojo's sign-off: cross-binding + deploy provenance + on-chain launch round-trip (~$5k FDV)
    !!l.padLockerBinding &&
    l.padLockerBinding.toLowerCase() === l.locker.toLowerCase() &&
    !!l.lockerFactoryBinding &&
    l.lockerFactoryBinding.toLowerCase() === l.pad.toLowerCase() &&
    isRealTxHash(l.deployTx) &&
    !!l.launchRoundTripFdv
  );
}

function positiveInteger(value?: string): boolean {
  try {
    return !!value && BigInt(value) > 0n;
  } catch {
    return false;
  }
}

/** Independent V3 trade release gate: both deployed runtime hashes, a real directional quote through
 * QuoterV2, and a successful funded exactInputSingle transaction to the configured SwapRouter02. */
function v3TradeProven(row: V3ChainRow, ev: V3ChainEvidence | undefined): boolean {
  const trade = ev?.trade;
  return (
    !!trade &&
    isRealAddress(row.swapRouter) &&
    isRealAddress(row.quoter) &&
    trade.swapRouter.toLowerCase() === row.swapRouter.toLowerCase() &&
    trade.quoter.toLowerCase() === row.quoter.toLowerCase() &&
    trade.swapRouterCodeHash?.toLowerCase() === row.swapRouterCodeHash.toLowerCase() &&
    trade.quoterCodeHash?.toLowerCase() === row.quoterCodeHash.toLowerCase() &&
    trade.quoteSmoke.tokenIn?.toLowerCase() === row.numeraire.address.toLowerCase() &&
    trade.quoteSmoke.fee === row.feeTier &&
    positiveInteger(trade.quoteSmoke.amountIn) &&
    positiveInteger(trade.quoteSmoke.amountOut) &&
    trade.quoteSmoke.routerAmountOut === trade.quoteSmoke.amountOut &&
    isRealAddress(trade.quoteSmoke.smokeAccount) &&
    !!trade.quoteSmoke.atBlock &&
    isRealTxHash(trade.tradeSmoke.txHash) &&
    !!trade.tradeSmoke.atBlock
  );
}

/** Derive a V3 chain's launch and trade capabilities independently. `ev` is injectable for tests;
 * defaults to the generated live-chain artifact. */
export function deriveV3Capability(
  row: V3ChainRow,
  ev: V3ChainEvidence | undefined = CHAIN_EVIDENCE_V3[row.id],
): ChainCapability {
  // Metadata must be real before 'live' (kami #3) — the row is source until gojo verifies the chain.
  const metadataReady = row.explorer.length > 0 && row.nativeSymbol.length > 0;
  const readSmoke = !!ev?.readSmoke && ev.chainId === row.id;
  // LIVE requires: canonical infra (derived vs row) AND Hyde deployed+signed AND metadata AND read smoke.
  const launchEnabled = v3InfraProven(row, ev) && v3LaunchProven(row, ev) && metadataReady && readSmoke;
  const tradeReady = launchEnabled && v3TradeProven(row, ev);
  const status: ChainStatus = launchEnabled ? "live" : "coming";
  return {
    id: row.id,
    name: row.name,
    shortName: row.shortName,
    logo: row.logo,
    nativeSymbol: row.nativeSymbol,
    explorer: row.explorer,
    status,
    role: tradeReady ? row.role : "launch",
    engine: "v3-single-sided",
    numeraire: row.numeraire,
    browse: { kind: "hyde-launches", markets: [] },
    trade: tradeReady
      ? {
          engine: "v3-single-sided",
          swapRouter: row.swapRouter,
          quoter: row.quoter,
          feeTier: row.feeTier,
          numeraire: row.numeraire,
        }
      : null,
    smoke: { read: readSmoke, trade: tradeReady },
    evidence: ev, // expose V3 evidence (kami #4) — no longer discarded
  };
}

