/** All engine capabilities for a chain (0, 1, or 2). Empty ⇒ the chain isn't in the registry. */
export function chainEngineCapabilities(
  chainId: number,
  caps: ChainCapability[] = chainCapabilities(),
): ChainCapability[] {
  return caps.filter((c) => c.id === chainId);
}

/** The capability for a specific (chainId, engine). Unknown pair ⇒ honestly 'unsupported' — the fail-closed
 *  answer the selector renders as a disabled engine button (e.g. V4 on a V3-only chain). */
export function chainEngineCapability(
  chainId: number,
  engine: LaunchEngine,
  caps: ChainCapability[] = chainCapabilities(),
): ChainCapability | { id: number; engine: LaunchEngine; status: "unsupported" } {
  return caps.find((c) => c.id === chainId && c.engine === engine) ?? { id: chainId, engine, status: "unsupported" };
}

/** Back-compat single-chain lookup — returns the FIRST engine's capability for a chain. Prefer the
 *  engine-aware lookups above when a specific engine matters (a chain can now expose more than one). */
export function chainCapability(chainId: number): ChainCapability | { id: number; status: "unsupported" } {
  const hit = chainEngineCapabilities(chainId)[0];
  return hit ?? { id: chainId, status: "unsupported" };
}

