const ZERO = "0x0000000000000000000000000000000000000000";
/** Placeholder addresses in constants.ts are short mnemonic hex (beef/cafe/f00d/…)
 *  left-padded with zeros — every REAL address has a non-zero high half. This
 *  predicate is the fail-closed test: unknown/zero/placeholder ⇒ not real. */
function isRealAddress(addr?: string): boolean {
  if (!addr || addr === ZERO) return false;
  return !/^0x0{20,}/i.test(addr);
}
/** A real 32-byte tx hash (deploy/trade provenance) — not zero, correct width. */
function isRealTxHash(h?: string): boolean {
  return !!h && /^0x[0-9a-fA-F]{64}$/.test(h) && !/^0x0{64}$/.test(h);
}

/** Execution path is PROVEN, not configured: the configured gateway address must
 *  match the evidence entry, whose deployed-bytecode facts (executeSwap selector
 *  + embedded UniversalRouter immutable) came from a live getCode probe. */
function executionPathProven(net: NetworkConfig, v4: V4Contracts | undefined, ev: ChainEvidence | undefined): boolean {
  if (!v4 || !isGatewayLive(net.id)) return false;
  const gw = ev?.gateway;
  if (!gw) return false;
  return (
    gw.address.toLowerCase() === v4.gateway.toLowerCase() &&
    gw.codeBytes > 0 &&
    gw.hasExecuteSwapSelector &&
    gw.embedsUniversalRouter
  );
}

function deriveCapability(net: NetworkConfig, shortName: string, role: ChainRole, logo: string): ChainCapability {
  const v4 = V4_CONTRACTS_BY_CHAIN[net.id];
  const ev = CHAIN_EVIDENCE[net.id];

  const configComplete =
    !!v4 &&
    isRealAddress(v4.poolManager) &&
    isRealAddress(v4.universalRouter) &&
    isRealAddress(v4.quoter) &&
    isRealAddress(v4.permit2) &&
    isRealAddress(v4.stateView) &&
    isRealAddress(net.weth) &&
    net.rpcUrl.length > 0 &&
    net.explorerUrl.length > 0 &&
    net.tokens.length > 0;

  // A market is only exposed if the APP'S OWN encoder reproduces its proven
  // poolId (kami 23091: evidence PoolKey ↔ encoded PoolKey regression). An
  // unreproducible market means encoder drift — excluded, loudly.
  const markets = (ev?.markets ?? []).filter((m) => {
    const ok = evidencePoolIdMatches(m);
    if (!ok) console.error(`[chainRegistry] market ${m.symbol} on ${net.name}: evidence poolId not reproducible by app encoder — EXCLUDED`);
    return ok;
  });
  const smoke = {
    read: !!ev?.readSmoke && ev.chainId === net.id,
    trade: !!ev?.tradeSmoke && ev.chainId === net.id,
  };

  const tradeReady = configComplete && executionPathProven(net, v4, ev);
  const marketsReady = role === "launch+trade" ? true : markets.length > 0;

  const status: ChainStatus =
    tradeReady && marketsReady && smoke.read && smoke.trade ? "live" : "coming";

  return {
    id: net.id,
    name: net.name,
    shortName,
    logo,
    nativeSymbol: net.currencySymbol,
    explorer: net.explorerUrl,
    status,
    role,
    engine: "v4-hook",
    // The V4 line prices in WETH (18-dec, native — not USD-pegged).
    numeraire: { address: net.weth, symbol: "WETH", decimals: 18, displayDecimals: 8, usdPegged: false },
    browse:
      role === "launch+trade"
        ? { kind: "hyde-launches", markets: [] }
        : { kind: "curated-markets", markets },
    trade: tradeReady && v4 ? { engine: "v4-hook", network: net, contracts: v4 } : null,
    smoke,
    evidence: ev,
  };
}

